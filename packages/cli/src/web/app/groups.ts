/** The agent's log of a run, cut into the run's steps by the time each step went on. */
import type { GateDetail, LogEntry, Visit } from "../../tui/session";

export interface Group {
  key: string;
  visit?: Visit;
  entries: LogEntry[];
}

/** The entries of each step, by the time the step went on; what came before every step goes first. */
export function groupsOf(d: GateDetail): Group[] {
  const log = d.agentLog ?? [];
  const timed = d.visits.map((v, i) => ({ v, i })).filter(({ v }) => v.attempt.from !== undefined);
  if (timed.length === 0) return log.length > 0 ? [{ key: "all", entries: log }] : [];
  const groups: Group[] = timed.map(({ v, i }) => ({ key: `${i}`, visit: v, entries: [] }));
  const before: LogEntry[] = [];
  for (const e of log) {
    // The latest step that had begun by then and had not ended; an agent's step wins over a command's.
    let at: number | undefined;
    timed.forEach(({ v }, j) => {
      const from = v.attempt.from as number;
      const to = v.attempt.to ?? Number.POSITIVE_INFINITY;
      if (e.ts < from || e.ts > to) return;
      const held = at === undefined ? undefined : timed[at]?.v;
      if (held === undefined || v.kind === "agent" || held.kind !== "agent") at = j;
    });
    if (at === undefined) {
      if (e.ts < (timed[0]?.v.attempt.from ?? 0)) before.push(e);
      else groups[groups.length - 1]?.entries.push(e);
    } else groups[at]?.entries.push(e);
  }
  const shown = groups.filter((g) => g.entries.length > 0 || g.visit?.state === "running");
  return before.length > 0 ? [{ key: "before", entries: before }, ...shown] : shown;
}

/** What Claude Code puts into a conversation as the person's turn, though the person did not write it. */
export type Notice =
  | { kind: "task"; title: string; status?: string; result?: string }
  | { kind: "notice"; tag: string; text: string };

/** The tags Claude Code wraps its own lines in; any other tag with a hyphen is read as one of them too. */
const NOTICE_TAGS = new Set([
  "system-reminder",
  "command-name",
  "command-message",
  "command-args",
  "local-command-stdout",
  "local-command-stderr",
  "local-command-caveat",
  "user-prompt-submit-hook",
  "bash-input",
  "bash-stdout",
  "bash-stderr",
]);

const field = (text: string, tag: string): string | undefined => {
  const m = new RegExp(`<${tag}>([\\s\\S]*?)(?:</${tag}>|$)`).exec(text);
  const value = m?.[1]?.trim();
  return value === undefined || value === "" ? undefined : value;
};

/**
 * A turn of the person that Claude Code wrote: a background task that ended, a reminder, the output of a
 * local command. Anything else is the person's own words. The text may be a preview cut short.
 */
export function noticeOf(text: string): Notice | undefined {
  const t = text.trimStart();
  if (t.startsWith("<task-notification>")) {
    const summary = field(t, "summary") ?? "A background task ended";
    const named = /"([^"]+)"/.exec(summary)?.[1];
    const status = field(t, "status");
    const result = field(t, "result");
    return {
      kind: "task",
      title: named ?? summary,
      ...(status === undefined ? {} : { status }),
      ...(result === undefined ? {} : { result }),
    };
  }
  const tag = /^<([a-z][a-z0-9-]*)>/.exec(t)?.[1];
  if (tag !== undefined && (NOTICE_TAGS.has(tag) || tag.includes("-"))) {
    return { kind: "notice", tag, text: t };
  }
  if (t.startsWith("Caveat: The messages below were generated by the user")) {
    return { kind: "notice", tag: "local-command-caveat", text: t };
  }
  return undefined;
}
